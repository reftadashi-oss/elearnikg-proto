// ---- 乱数（毎回ちがう問題にする） ----
const rand = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = rand(0, i); [a[i], a[j]] = [a[j], a[i]]; } return a; };

// 10問を作る。avoid＝前の回に出した問題（続けて同じ問題にしない）
function pickTen(pool, avoid) {
  const fresh = shuffle(pool.filter(q => !avoid.has(q.key)));
  const old = shuffle(pool.filter(q => avoid.has(q.key)));
  return fresh.concat(old).slice(0, 10);
}

