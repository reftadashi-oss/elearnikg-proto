function mathPool(make) { const m = new Map(); for (let i = 0; i < 400 && m.size < 60; i++) { const q = make(); m.set(q.key, q); } return [...m.values()]; }
const add10 = () => { const a = rand(1, 9), b = rand(1, 10 - a); return { key: `${a}+${b}`, text: `${a} ＋ ${b} ＝`, boxes: [''], answer: [a + b] }; };
const addCarry = () => { let a, b; do { a = rand(2, 9); b = rand(2, 9); } while (a + b < 11); return { key: `${a}+${b}`, text: `${a} ＋ ${b} ＝`, boxes: [''], answer: [a + b] }; };
const divRem = () => { const d = rand(2, 9), q = rand(1, 9), r = rand(1, d - 1), n = d * q + r; return { key: `${n}/${d}`, text: `${n} ÷ ${d} ＝`, boxes: ['', 'あまり'], answer: [q, r] }; };

