// 算数の 特殊算（文章題の とき方）を ふやす（2026年11月19日）。content_add.js の あとに 読む（シリーズ m17 に 足す）。
// 学年の 考え方（Claude の 案・仮）：その 学年までに 学校で 習う 計算で 解ける ところ。
//   4年：日暦算・方陣算（＋もとから ある 植木算・和差算・分配算・過不足算・鶴亀算）
//   5年：平均算・消去算・通過算・損益算（＋年齢算・旅人算・流水算）　6年：相当算・濃度算・時計算・ニュートン算（＋仕事算）
// 問題は プログラムが 作り、答えも プログラムが 計算する。本や 過去問からは 写していない。
(() => {
  const math = SUBJECTS.find(s => s.id === 'math'), se = math && math.series.find(s => s.id === 'm17'); if (!se) return;
  const pick = a => a[rand(0, a.length - 1)];
  const f = s => String(s).replace(/([一-鿿々]+)\(([ぁ-ゖー]+)\)/g, '{$1|$2}');
  const wp = s => `<span class="wp">${f(s)}</span>`;
  const big = s => `<span class="big">${s}</span>`;
  const retry = g => () => { for (let i = 0; i < 500; i++) { const x = g(); if (x) return x; } return null; };
  const q = (text, ans) => ({ key: text, text: wp(text), boxes: [''], answer: [ans] });
  const choice = (stem, opts, correct) => { const o = shuffle([...new Set(opts)]); return { key: stem + '#' + correct, text: `${wp(stem)}<br><span class="ch">${o.map((x, i) => `<b>${i + 1}</b> ${f(x)}`).join('　')}</span>`, boxes: [''], answer: [o.indexOf(correct) + 1] }; };
  const ten = gen => () => { const m = new Map(); for (let i = 0; i < 400 && m.size < 10; i++) { const x = gen(); if (x && !m.has(x.key)) m.set(x.key, x); } const a = [...m.values()]; for (let i = 0; a.length < 10; i++) a.push(a[i]); return shuffle(a); };
  const ENTER = 'こたえを テンキーで いれて、Enterを おそう。';
  const gcd = (a, b) => b ? gcd(b, a % b) : a;
  let n = 0;
  const add = (name, grade, gen, ...lecture) => { const id = `m17-t${++n}`; UNITS[id] = { id, subject: 'math', series: 'm17', name: f(name), col: UNITS[se.units[0]] ? UNITS[se.units[0]].col : '', pass: 0.8, make: ten(gen), lecture: lecture.map(f), grade }; se.units.push(id); };

  // ===== 4年：日暦算 =====
  const YO = [['日', 'にち'], ['月', 'げつ'], ['火', 'か'], ['水', 'すい'], ['木', 'もく'], ['金', 'きん'], ['土', 'ど']].map(([x, r]) => `${x}(${r})曜日(ようび)`);
  const ML = [['1月(がつ)', 31], ['4月(がつ)', 30], ['5月(がつ)', 31], ['6月(がつ)', 30], ['7月(がつ)', 31], ['9月(がつ)', 30], ['10月(がつ)', 31], ['11月(がつ)', 30]];
  add('日暦算(にちれきざん)（曜日(ようび)）', 4, () => {
    const d0 = rand(0, 6), opts = a => [YO[a], ...shuffle(YO.filter((_, i) => i !== a)).slice(0, 2)];
    return pick([
      () => { const day = rand(8, 30), a = (d0 + day - 1) % 7; return choice(`ある 月(つき)の 1日(ついたち)が ${YO[d0]}です。その 月(つき)の ${day}日(にち)は 何曜日(なんようび)？`, opts(a), YO[a]); },
      () => { const [m, L] = pick(ML), day = rand(1, 28), a = (d0 + L) % 7; return choice(`${m}${day}日(にち)が ${YO[d0]}です。つぎの 月(つき)の ${day}日(にち)は 何曜日(なんようび)？（${m}は ${L}日(にち)まで）`, opts(a), YO[a]); },
      () => { const k = rand(10, 60), a = (d0 + k) % 7; return choice(`きょうは ${YO[d0]}です。${k}日後(にちご)は 何曜日(なんようび)？`, opts(a), YO[a]); },
    ])();
  }, `曜日(ようび)は ${big('7日(にち)')}ごとに くりかえすよ。<br>${big('何日後(なんにちご) ÷ 7 の あまり')}だけ、曜日(ようび)を すすめよう。`,
    `1日(ついたち)から ${big('20日(にち)')}までは 19日後(にちご)。19 ÷ 7 ＝ 2 あまり 5 → 5つ すすめる。<br>こたえの 番号(ばんごう)を テンキーで いれよう。`);

  // ===== 4年：方陣算 =====
  add('方陣算(ほうじんざん)', 4, () => {
    const s = rand(4, 15);
    return pick([
      q(`ご石(いし)を、1辺(ぺん)に ${s}こずつ ならべて、中(なか)まで つまった 正方形(せいほうけい)を 作(つく)ります。ご石(いし)は ぜんぶで □こ`, s * s),
      q(`ご石(いし)を、1辺(ぺん)に ${s}こずつ ならべて 正方形(せいほうけい)を 作(つく)りました。いちばん 外(そと)側(がわ)の 1周(しゅう)の ご石(いし)は □こ`, 4 * s - 4),
      q(`中(なか)まで つまった 正方形(せいほうけい)に ご石(いし)を ならべたら、いちばん 外(そと)側(がわ)の 1周(しゅう)が ${4 * s - 4}こでした。ご石(いし)は ぜんぶで □こ`, s * s),
    ]);
  }, `中(なか)まで つまった 正方形(せいほうけい)は ${big('1辺(ぺん) × 1辺(ぺん)')}こ。`,
    `外(そと)側(がわ)の 1周(しゅう)は ${big('（1辺(ぺん) − 1）× 4')}。かどを 2回(かい) 数(かぞ)えないように しよう。<br>${ENTER}`);

  // ===== 5年：平均算 =====
  add('平均算(へいきんざん)', 5, retry(() => {
    const k = rand(3, 5), A = rand(60, 85), t = pick([0, 1]);
    if (t === 0) { const B = rand(50, 100), T = k * A + B; if (T % (k + 1)) return null; return q(`${k}回(かい)の テストの 平均(へいきん)は ${A}点(てん)でした。${k + 1}回目(かいめ)に ${B}点(てん)を とると、${k + 1}回(かい)の 平均(へいきん)は □点(てん)`, T / (k + 1)); }
    const C = A + rand(1, 5), x = (k + 1) * C - k * A; if (x > 100) return null; return q(`${k}回(かい)の テストの 平均(へいきん)は ${A}点(てん)です。${k + 1}回(かい)の 平均(へいきん)を ${C}点(てん)に するには、${k + 1}回目(かいめ)に □点(てん) とれば よい`, x);
  }), `${big('合計(ごうけい) ＝ 平均(へいきん) × 回数(かいすう)')}。平均算(へいきんざん)は、まず 合計(ごうけい)を 出(だ)すのが ポイント。`,
    `${big('70点(てん)が 3回(かい) → 合計(ごうけい) 210点(てん)')}<br>${ENTER}`);

  // ===== 5年：消去算 =====
  const FR = [['りんご', 'みかん'], ['ノート', 'えんぴつ'], ['ケーキ', 'プリン'], ['おにぎり', 'お茶(ちゃ)']];
  add('消去算(しょうきょざん)', 5, () => {
    const [A, B] = pick(FR), a = rand(8, 20) * 10, b = rand(3, 12) * 10, p = rand(1, 3), x = rand(1, 3), y = x + rand(1, 3);
    return pick([
      q(`${A} ${p}こと ${B} ${x}こで ${p * a + x * b}円(えん)、${A} ${p}こと ${B} ${y}こで ${p * a + y * b}円(えん)です。${B} 1こは □円(えん)`, b),
      q(`${A} ${p}こと ${B} ${x}こで ${p * a + x * b}円(えん)、${A} ${p}こと ${B} ${y}こで ${p * a + y * b}円(えん)です。${A} 1こは □円(えん)`, a),
      q(`${A} 1こと ${B} 2こで ${a + 2 * b}円(えん)、${A} 2こと ${B} 2こで ${2 * a + 2 * b}円(えん)です。${A} 1こは □円(えん)`, a),
    ]);
  }, `2つの 式(しき)を くらべて、${big('おなじ 数(かず)の ものを けす')}（消去(しょうきょ)）と、のこりの ねだんが わかるよ。`,
    `りんご1こ＋みかん2こ＝200円(えん)、りんご1こ＋みかん4こ＝300円(えん)<br>→ ちがいの みかん2こが 100円(えん)。みかん1こは 50円(えん)。<br>${ENTER}`);

  // ===== 5年：通過算 =====
  add('通過算(つうかざん)', 5, retry(() => {
    const v = rand(10, 30), L = rand(8, 30) * 10, t = rand(10, 60), T = v * t - L; if (T < 50) return null;
    return pick([
      q(`長(なが)さ ${L}mの 電車(でんしゃ)が、秒速(びょうそく) ${v}mで 走(はし)って います。長(なが)さ ${T}mの 鉄橋(てっきょう)を わたり 始(はじ)めてから わたり 終(お)わるまで □秒(びょう)`, t),
      ...(L % v === 0 ? [q(`長(なが)さ ${L}mの 電車(でんしゃ)が、秒速(びょうそく) ${v}mで 走(はし)って います。電柱(でんちゅう)の 前(まえ)を 通(とお)りすぎるのに □秒(びょう)`, L / v)] : []),
      q(`秒速(びょうそく) ${v}mの 電車(でんしゃ)が、長(なが)さ ${T}mの 鉄橋(てっきょう)を わたり 始(はじ)めてから わたり 終(お)わるまで ${t}秒(びょう) かかりました。電車(でんしゃ)の 長(なが)さは □m`, L),
    ]);
  }), `鉄橋(てっきょう)を わたる ときに 電車(でんしゃ)が すすむ きょりは ${big('鉄橋(てっきょう)の 長(なが)さ ＋ 電車(でんしゃ)の 長(なが)さ')}。`,
    `電柱(でんちゅう)の 前(まえ)を 通(とお)る ときは、電車(でんしゃ)の 長(なが)さ だけ すすむ。<br>${big('時間(じかん) ＝ きょり ÷ 速(はや)さ')}<br>${ENTER}`);

  // ===== 5年：損益算 =====
  add('損益算(そんえきざん)', 5, () => {
    const C = rand(5, 40) * 100, p = rand(1, 5), d = rand(1, 3), P = C * (10 + p) / 10;
    return pick([
      q(`原価(げんか) ${C}円(えん)の 品物(しなもの)に、${p}割(わり)の 利益(りえき)を 見(み)こんで 定価(ていか)を つけました。定価(ていか)は □円(えん)`, P),
      q(`定価(ていか) ${C}円(えん)の 品物(しなもの)を ${d}割引(わりび)きで 売(う)ります。売(う)りねは □円(えん)`, C * (10 - d) / 10),
      q(`原価(げんか) ${C}円(えん)の 品物(しなもの)に ${p}割(わり)の 利益(りえき)を 見(み)こんで 定価(ていか)を つけ、その 定価(ていか)の 1割引(わりび)きで 売(う)りました。売(う)りねは □円(えん)`, P * 9 / 10),
    ]);
  }, `${big('原価(げんか)')}：仕入(しい)れた ねだん　${big('定価(ていか)')}：つけた ねだん　${big('売(う)りね')}：本当(ほんとう)に 売(う)った ねだん`,
    `${big('2割(わり)の 利益(りえき) → 原価(げんか) × 1.2')}　${big('1割引(わりび)き → 定価(ていか) × 0.9')}<br>${ENTER}`);

  // ===== 6年：相当算 =====
  add('相当算(そうとうざん)', 6, retry(() => {
    const b = rand(3, 9), a = rand(1, b - 1), k = rand(4, 20); if (gcd(a, b) !== 1) return null;
    return pick([
      q(`本(ほん)を、全体(ぜんたい)の ${a}/${b} 読(よ)みました。のこりは ${(b - a) * k}ページです。この 本(ほん)は □ページ`, b * k),
      q(`持(も)って いた お金(かね)の ${a}/${b} で 本(ほん)を 買(か)ったら、${(b - a) * k * 10}円(えん) のこりました。はじめに 持(も)って いた お金(かね)は □円(えん)`, b * k * 10),
    ]);
  }), `全体(ぜんたい)を ${big('1')}と して、のこりが 全体(ぜんたい)の どれだけに ${big('相当(そうとう)')}するかを 考(かんが)えるよ。`,
    `全体(ぜんたい)の 2/5 を 読(よ)んだ → のこりは 3/5。<br>${big('全体(ぜんたい) ＝ のこり ÷ 3/5')}<br>${ENTER}`);

  // ===== 6年：濃度算 =====
  add('濃度算(のうどざん)（食塩水(しょくえんすい)）', 6, retry(() => {
    const t = rand(0, 2);
    if (t === 0) { const p = pick([2, 4, 5, 8, 10, 12, 15, 20, 25]), T = rand(1, 10) * 100, S = T * p / 100; return q(`水(みず) ${T - S}gに 食塩(しょくえん) ${S}gを とかしました。この 食塩水(しょくえんすい)の 濃(こ)さは □%`, p); }
    if (t === 1) { const p = pick([3, 4, 5, 6, 8, 10, 12, 15]), T = rand(1, 8) * 100; return q(`${p}%の 食塩水(しょくえんすい) ${T}gに ふくまれる 食塩(しょくえん)は □g`, T * p / 100); }
    const a = pick([2, 4, 5, 6, 8]), b = pick([10, 12, 15, 20]), x = rand(1, 5) * 100, y = rand(1, 5) * 100, S = a * x + b * y; if (S % (x + y)) return null;
    return q(`${a}%の 食塩水(しょくえんすい) ${x}gと、${b}%の 食塩水(しょくえんすい) ${y}gを まぜると、□%の 食塩水(しょくえんすい)に なります`, S / (x + y));
  }), `${big('濃(こ)さ（%） ＝ 食塩(しょくえん) ÷ 食塩水(しょくえんすい) × 100')}。食塩水(しょくえんすい)は 水(みず)と 食塩(しょくえん)を あわせた 重(おも)さ。`,
    `まぜる ときは、${big('食塩(しょくえん)の 重(おも)さ どうしを たす')}。濃(こ)さを そのまま たしては だめ。<br>${ENTER}`);

  // ===== 6年：時計算 =====
  add('時計算(とけいざん)', 6, retry(() => {
    const h = rand(1, 11);
    if (Math.random() < 0.4) { const d = 30 * h; return q(`${h}時(じ)ちょうどに、時計(とけい)の 長(なが)い 針(はり)と 短(みじか)い 針(はり)が 作(つく)る 小(ちい)さい ほうの 角(かく)は □度(ど)`, Math.min(d, 360 - d)); }
    const m = rand(1, 29) * 2, d = Math.abs(30 * h - 5.5 * m) % 360, a = Math.min(d, 360 - d);
    return q(`${h}時(じ)${m}分(ふん)に、時計(とけい)の 長(なが)い 針(はり)と 短(みじか)い 針(はり)が 作(つく)る 小(ちい)さい ほうの 角(かく)は □度(ど)`, a);
  }), `長(なが)い 針(はり)は 1分(ぷん)で ${big('6度(ど)')}、短(みじか)い 針(はり)は 1分(ぷん)で ${big('0.5度(ど)')} すすむ。`,
    `${big('3時(じ)ちょうど')}は 30度(ど) × 3 ＝ 90度(ど)。<br>○時(じ)□分(ふん)は、短(みじか)い 針(はり)が 30 × ○ ＋ 0.5 × □度(ど)、長(なが)い 針(はり)が 6 × □度(ど)。その ちがいを 出(だ)そう。<br>${ENTER}`);

  // ===== 6年：ニュートン算 =====
  add('ニュートン算(ざん)', 6, retry(() => {
    const r = rand(1, 5), c = r + rand(1, 6), t = rand(5, 30), N = (c - r) * t;
    return pick([
      q(`チケット売(う)り場(ば)に ${N}人(にん)が ならんで います。1分(ぷん)ごとに ${r}人(にん)ずつ ふえます。窓口(まどぐち)では 1分(ぷん)に ${c}人(にん)ずつ 売(う)ります。行列(ぎょうれつ)が なくなるのは □分後(ふんご)`, t),
      ...(c % 2 === 0 ? [] : [q(`チケット売(う)り場(ば)に ${(2 * c - r) * t}人(にん)が ならんで います。1分(ぷん)ごとに ${r}人(にん)ずつ ふえます。1つの 窓口(まどぐち)で 1分(ぷん)に ${c}人(にん)ずつ 売(う)ります。窓口(まどぐち)を 2つ あけると、行列(ぎょうれつ)が なくなるのは □分後(ふんご)`, t)]),
    ]);
  }), `ならぶ 人(ひと)が ふえながら、へって いく 問題(もんだい)。${big('1分(ぷん)で へる 人数(にんずう) ＝ 売(う)る 人数(にんずう) − ふえる 人数(にんずう)')}`,
    `${big('時間(じかん) ＝ はじめの 人数(にんずう) ÷ 1分(ぷん)で へる 人数(にんずう)')}<br>${ENTER}`);
})();
